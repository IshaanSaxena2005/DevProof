/**
 * Browser-E2E account passwords — deliberately never committed.
 *
 * GitGuardian flagged the literal passwords this module replaces. Test
 * credentials do not belong in the repository even when the accounts are
 * disposable: anyone with read access can reuse the values, and committed
 * literals teach scanners to tolerate this pattern. Instead:
 *
 *  - `E2E_MAIN_PASSWORD` / `E2E_ISOLATION_PASSWORD` override everything, for
 *    pointing the suite (via `E2E_BASE_URL`) at a stack whose accounts were
 *    created by an earlier run and therefore keep their earlier passwords.
 *  - Otherwise a fresh random password per run is generated by whichever
 *    process loads this module first — always Playwright's global setup,
 *    which completes before any worker starts — and persisted to
 *    `e2e/.auth/credentials.json`. That directory is git-ignored alongside
 *    the saved sessions, and workers read the same file, so global setup and
 *    every spec agree on one password per run.
 *
 * A per-run value is safe because e2e/start-backend.mjs drops and recreates
 * the isolated database on every run and global setup registers the accounts
 * from scratch each time. These passwords can only ever authenticate against
 * that disposable database — never against a real environment.
 */
import { randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/** Git-ignored, next to the saved sessions the suite already writes here. */
export const CREDENTIALS_PATH = path.join("e2e", ".auth", "credentials.json");

export interface AccountPasswords {
  main: string;
  isolation: string;
}

/** A fresh throwaway password for a one-off account a spec registers itself. */
export function generatedTestPassword(): string {
  return randomBytes(18).toString("base64url");
}

function loadStored(): AccountPasswords | null {
  try {
    const parsed = JSON.parse(readFileSync(CREDENTIALS_PATH, "utf8")) as Partial<AccountPasswords>;
    if (typeof parsed.main === "string" && typeof parsed.isolation === "string") {
      return { main: parsed.main, isolation: parsed.isolation };
    }
    return null;
  } catch {
    // Missing or unreadable file: generate a fresh store below.
    return null;
  }
}

/**
 * Resolve this run's account passwords, in priority order:
 * environment overrides, the per-run store, or a newly generated store.
 *
 * Throws when only one of the two overrides is set — a half-configured run
 * would fail later with a confusing login error instead of a clear message.
 */
export function resolveAccountPasswords(): AccountPasswords {
  const main = process.env.E2E_MAIN_PASSWORD;
  const isolation = process.env.E2E_ISOLATION_PASSWORD;

  if (main && isolation) return { main, isolation };
  if (main || isolation) {
    throw new Error(
      "[e2e] Set both E2E_MAIN_PASSWORD and E2E_ISOLATION_PASSWORD, or neither — " +
        "a half-configured override would surface later as an unexplained login failure."
    );
  }

  const stored = loadStored();
  if (stored) return stored;

  const fresh: AccountPasswords = { main: generatedTestPassword(), isolation: generatedTestPassword() };
  mkdirSync(path.dirname(CREDENTIALS_PATH), { recursive: true });
  writeFileSync(CREDENTIALS_PATH, `${JSON.stringify(fresh, null, 2)}\n`, { mode: 0o600 });
  return fresh;
}
